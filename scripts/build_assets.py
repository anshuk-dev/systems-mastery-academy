#!/usr/bin/env python3
"""Validate course JSON data + verified primary sources, generate JS bundle, and render Markdown docs."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
CURRICULUM_DIR = ROOT / "curriculum"
ASSESSMENTS_DIR = ROOT / "assessments"

QUESTION_FILES = [
    "questions-integration.json",
    "questions-modularity.json",
    "questions-optimization.json",
    "questions-scalability.json",
    "questions-capstone.json",
]

LETTERS = ["A", "B", "C", "D"]


def validate_sources(items: list[dict], owner_id: str) -> None:
    assert isinstance(items, list) and len(items) >= 1, f"{owner_id}: missing verified sources"
    for s in items:
        assert s.get("title") and s.get("author") and s.get("url", "").startswith("https://"), (
            f"{owner_id}: malformed source entry {s}"
        )


def load_and_validate() -> tuple[dict, list[dict]]:
    pillars_data = json.loads((DATA_DIR / "pillars.json").read_text(encoding="utf-8"))
    pillars = pillars_data.get("pillars", [])
    assert len(pillars) == 5, f"Expected 5 pillars, found {len(pillars)}"

    pillar_ids = {p["id"] for p in pillars}
    seen_lesson_ids = set()
    for p in pillars:
        assert p.get("lessons"), f"Pillar {p['id']} has no lessons"
        for lesson in p["lessons"]:
            lid = lesson["id"]
            assert lid not in seen_lesson_ids, f"Duplicate lesson id: {lid}"
            seen_lesson_ids.add(lid)
            for field in ("title", "knowledge", "wisdom", "tradeoffs", "antiPatterns", "heuristic"):
                assert lesson.get(field), f"Lesson {lid} missing {field}"
            validate_sources(lesson.get("sources", []), f"Lesson {lid}")

    questions: list[dict] = []
    seen_q_ids = set()
    for qfile in QUESTION_FILES:
        items = json.loads((DATA_DIR / qfile).read_text(encoding="utf-8"))
        for q in items:
            qid = q["id"]
            assert qid not in seen_q_ids, f"Duplicate question id: {qid}"
            seen_q_ids.add(qid)
            assert q["pillar"] in pillar_ids, f"{qid}: unknown pillar {q['pillar']}"
            assert len(q["options"]) == 4, f"{qid}: expected 4 options"
            cidx = q["correctIndex"]
            assert isinstance(cidx, int) and 0 <= cidx <= 3, f"{qid}: invalid correctIndex {cidx}"
            assert q.get("explanation"), f"{qid}: missing explanation"
            assert q.get("wisdomTakeaway"), f"{qid}: missing wisdomTakeaway"
            validate_sources(q.get("sources", []), f"Question {qid}")
            da = q.get("distractorAnalysis", {})
            for idx in range(4):
                key = str(idx)
                assert key in da, f"{qid}: missing distractorAnalysis[{key}]"
                if idx == cidx:
                    assert da[key].get("keyInsight"), f"{qid}: correct option {key} missing keyInsight"
                else:
                    assert da[key].get("trap") and da[key].get("whyWrong"), (
                        f"{qid}: distractor {key} missing trap or whyWrong"
                    )
            questions.append(q)

    return pillars_data, questions


def write_bundle(pillars_data: dict, questions: list[dict]) -> None:
    bundle = {
        "title": pillars_data["title"],
        "subtitle": pillars_data["subtitle"],
        "pillars": pillars_data["pillars"],
        "questions": questions,
    }
    (DATA_DIR / "questions.json").write_text(
        json.dumps(questions, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    js_content = (
        "// Auto-generated by scripts/build_assets.py from canonical JSON files in data/\n"
        f"window.COURSE_DATA = {json.dumps(bundle, indent=2, ensure_ascii=False)};\n"
    )
    (DATA_DIR / "course-bundle.js").write_text(js_content, encoding="utf-8")


def render_curriculum_markdown(pillars_data: dict) -> None:
    CURRICULUM_DIR.mkdir(parents=True, exist_ok=True)
    for pillar in pillars_data["pillars"]:
        lines = [
            f"# Pillar {pillar['number']}: {pillar['name']}",
            "",
            f"> **{pillar['tagline']}**",
            "",
            pillar["summary"],
            "",
            f"**Core Mental Model:** {pillar['mentalModel']}",
            "",
            "---",
            "",
        ]
        for lesson in pillar["lessons"]:
            lines.extend([
                f"## {lesson['title']} ({lesson['duration']})",
                "",
                "### Core Knowledge (Mechanics & Laws)",
                "",
            ])
            for k in lesson["knowledge"]:
                lines.append(f"- {k}")
            lines.extend(["", "### Principal Engineering Wisdom (Judgment & Trade-offs)", ""])
            for w in lesson["wisdom"]:
                lines.append(f"- {w}")
            lines.extend([
                "",
                "### Architectural Trade-off Matrix",
                "",
                "| Approach | Pros | Cons | When to Use |",
                "|---|---|---|---|",
            ])
            for t in lesson["tradeoffs"]:
                lines.append(f"| **{t['option']}** | {t['pros']} | {t['cons']} | {t['whenToUse']} |")
            lines.extend(["", "### Common Anti-Patterns", ""])
            for a in lesson["antiPatterns"]:
                lines.append(f"- {a}")
            lines.extend([
                "",
                f"> **Rule of Thumb:** {lesson['heuristic']}",
                "",
                "### Verified Primary Sources",
                "",
            ])
            for s in lesson["sources"]:
                lines.append(f"- [{s['title']}]({s['url']}) — {s['author']}")
            lines.extend(["", "---", ""])
        filename = f"{pillar['number']}-{pillar['id']}.md"
        (CURRICULUM_DIR / filename).write_text("\n".join(lines), encoding="utf-8")


def render_assessments_markdown(pillars_data: dict, questions: list[dict]) -> None:
    ASSESSMENTS_DIR.mkdir(parents=True, exist_ok=True)
    pillar_map = {p["id"]: p for p in pillars_data["pillars"]}
    grouped: dict[str, list[dict]] = {p["id"]: [] for p in pillars_data["pillars"]}
    for q in questions:
        grouped[q["pillar"]].append(q)

    for pid, qlist in grouped.items():
        pillar = pillar_map[pid]
        lines = [
            f"# Assessment & Distractor Analysis — {pillar['number']}: {pillar['name']}",
            "",
            f"{len(qlist)} scenario-based engineering questions grounded in verified primary engineering literature.",
            "",
            "---",
            "",
        ]
        for q in qlist:
            cidx = q["correctIndex"]
            lines.extend([
                f"## {q['id']} — {q['concept']} (`{q['difficulty']}`)",
                "",
                f"**Scenario:** {q['scenario']}",
                "",
                f"**Question:** {q['question']}",
                "",
            ])
            for idx, opt in enumerate(q["options"]):
                lines.append(f"- **{LETTERS[idx]}.** {opt}")
            lines.extend([
                "",
                "<details>",
                "<summary>Show Answer, Explanation, Distractor Analysis &amp; Verified Sources</summary>",
                "",
                f"**Correct Answer:** **{LETTERS[cidx]}**",
                "",
                f"**Explanation:** {q['explanation']}",
                "",
                "#### Option & Distractor Analysis",
                "",
            ])
            for idx in range(4):
                info = q["distractorAnalysis"][str(idx)]
                if idx == cidx:
                    lines.append(f"- **{LETTERS[idx]} (Correct — Key Insight):** {info['keyInsight']}")
                else:
                    lines.append(
                        f"- **{LETTERS[idx]} (Distractor — _{info['trap']}_):** {info['whyWrong']}"
                    )
            lines.extend([
                "",
                f"> **Wisdom Takeaway:** {q['wisdomTakeaway']}",
                "",
                "#### Verified Primary Sources",
                "",
            ])
            for s in q["sources"]:
                lines.append(f"- [{s['title']}]({s['url']}) — {s['author']}")
            lines.extend(["", "</details>", "", "---", ""])
        filename = f"{pillar['number']}-{pid}-qa.md"
        (ASSESSMENTS_DIR / filename).write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    pillars_data, questions = load_and_validate()
    write_bundle(pillars_data, questions)
    render_curriculum_markdown(pillars_data)
    render_assessments_markdown(pillars_data, questions)
    total_lessons = sum(len(p["lessons"]) for p in pillars_data["pillars"])
    unique_urls = {
        s["url"]
        for p in pillars_data["pillars"]
        for l in p["lessons"]
        for s in l["sources"]
    } | {s["url"] for q in questions for s in q["sources"]}
    print(
        f"Validated and built assets: {len(pillars_data['pillars'])} pillars, "
        f"{total_lessons} lessons, {len(questions)} questions, {len(unique_urls)} verified primary source URLs."
    )


if __name__ == "__main__":
    main()
